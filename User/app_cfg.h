#ifndef __APP_CFG_H
#define __APP_CFG_H

#include <stdint.h>

/*
*********************************************************************************************************
*                                            TASK PRIORITIES
*
*  uCOS-III 里数值越小优先级越高。
*  电机任务排在 UI 之上：松开按键就是要停，这个动作不能排在画屏和
*  触摸屏软件 I2C 后面。Motor_Task 每周期只做几十微秒的活
*  （两次 GPIO 读 + 几次寄存器写），不会真正饿着 UI。
*
*  注意别排到 1 或 2：那是 uCOS 内核自己的 tick 任务和启动任务。
*********************************************************************************************************
*/
#define MOTOR_TASK_PRIO        3
#define UI_TASK_PRIO           4

/*
*********************************************************************************************************
*                                            TASK STACK SIZES
*********************************************************************************************************
*/
#define MOTOR_TASK_STK_SIZE    512
#define UI_TASK_STK_SIZE       2048

#endif /* __APP_CFG_H */
