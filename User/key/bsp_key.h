#ifndef __BSP_KEY_H
#define __BSP_KEY_H

#include "stm32f4xx.h"

/*
*********************************************************************************************************
*                                        板载按键（长按语义）
*
*  与 CEMPES 原先的触摸交互不同，本工程的两个板载按键改成"按住才算数"：
*  Key_IsHeld() 返回消抖之后"此刻是否被按住"，而不是一次按下事件。
*
*  电平：两个按键都是按下 = 高电平（内部下拉）。
*  这个极性来自 ZHSX 上一版的 gpio.c，并且已在实机上验证过按键有效。
*********************************************************************************************************
*/

typedef enum {
    KEY_ID_FORWARD = 0,   /* KEY1 = PA0  → 正转 */
    KEY_ID_REVERSE = 1,   /* KEY2 = PC13 → 反转 */
    KEY_ID_COUNT
} KeyId_t;

#define KEY_SCAN_PERIOD_MS  10u
#define KEY_DEBOUNCE_MS     30u

/*
*********************************************************************************************************
*                                            接口
*********************************************************************************************************
*/
void        Key_Init(void);
void        Key_Scan(void);
uint8_t     Key_IsHeld(KeyId_t key);
uint8_t     Key_IsAnyHeld(void);
const char *Key_Name(KeyId_t key);

#endif /* __BSP_KEY_H */
